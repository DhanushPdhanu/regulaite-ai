"""generate_contracts.py
Generates 18 realistic legal contract PDFs for RegulAIte demo.
Each looks professional and balanced on surface read,
but contains hidden traps the AI agents must catch.

Run: cd regulaite && python contracts/generate_contracts.py
Output: 18 PDF files in regulaite/contracts/
"""

from fpdf import FPDF
import os
import textwrap

OUTPUT_DIR = os.path.join(os.path.dirname(__file__))


class ContractPDF(FPDF):
    def __init__(self, title: str):
        super().__init__()
        self.contract_title = title
        self.set_auto_page_break(auto=True, margin=20)
        self.add_page()
        self.set_margins(25, 20, 25)

    def header(self):
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(120, 120, 120)
        self.cell(0, 8, self.contract_title, align="R", new_x="LMARGIN", new_y="NEXT")
        self.set_text_color(0, 0, 0)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(150, 150, 150)
        self.cell(0, 8, f"Page {self.page_no()}", align="C")
        self.set_text_color(0, 0, 0)

    def add_title(self, text: str):
        self.set_font("Helvetica", "B", 14)
        self.ln(4)
        self.multi_cell(0, 8, text, align="C")
        self.ln(6)

    def add_subtitle(self, text: str):
        self.set_font("Helvetica", "I", 10)
        self.set_text_color(80, 80, 80)
        self.multi_cell(0, 6, text, align="C")
        self.set_text_color(0, 0, 0)
        self.ln(8)

    def add_section(self, number: str, heading: str):
        self.ln(4)
        self.set_font("Helvetica", "B", 11)
        self.multi_cell(0, 7, f"{number}  {heading}")
        self.ln(1)

    def add_clause(self, number: str, text: str):
        self.set_font("Helvetica", "", 10)
        wrapped = f"{number}   {text}"
        self.multi_cell(0, 6, wrapped)
        self.ln(2)

    def add_parties(self, party1: str, party2: str, date: str):
        self.set_font("Helvetica", "", 10)
        self.multi_cell(0, 6,
            f"This Agreement is entered into as of {date} between:\n"
            f"  Party A: {party1} (\"Client\")\n"
            f"  Party B: {party2} (\"Vendor\")\n"
            "collectively referred to as the \"Parties\".")
        self.ln(6)


def save(pdf: ContractPDF, filename: str):
    path = os.path.join(OUTPUT_DIR, filename)
    pdf.output(path)
    print(f"  Created: {filename}")


