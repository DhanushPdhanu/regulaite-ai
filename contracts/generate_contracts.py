def generate_all():
    print(f"\nGenerating {len(CONTRACTS)} legal contracts into: {OUTPUT_DIR}\n")
    for contract in CONTRACTS:
        pdf = ContractPDF(title=contract["title"])
        pdf.add_title(contract["title"])
        pdf.add_subtitle("CONFIDENTIAL - FOR REVIEW PURPOSES ONLY")
        pdf.add_parties(contract["party1"], contract["party2"], contract["date"])

        for sec_num, sec_heading, clauses in contract["sections"]:
            pdf.add_section(sec_num, sec_heading)
            for clause_num, clause_text in clauses:
                pdf.add_clause(f"{sec_num}.{clause_num.split('.')[-1]}", clause_text)

        pdf.add_section("SIGNATURES", "")
        pdf.add_clause("", f"For and on behalf of {contract['party1']}:")
        pdf.ln(8)
        pdf.add_clause("", "Authorised Signatory: _______________________")
        pdf.add_clause("", "Name & Designation:  _______________________")
        pdf.add_clause("", "Date:                _______________________")
        pdf.ln(8)
        pdf.add_clause("", f"For and on behalf of {contract['party2']}:")
        pdf.ln(8)
        pdf.add_clause("", "Authorised Signatory: _______________________")
        pdf.add_clause("", "Name & Designation:  _______________________")
        pdf.add_clause("", "Date:                _______________________")

        save(pdf, contract["filename"])

    print(f"\nDone. {len(CONTRACTS)} contracts generated.\n")


if __name__ == "__main__":
    generate_all()
